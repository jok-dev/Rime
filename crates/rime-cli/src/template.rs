//! `rime config-template`: a rime.toml that names every setting Rime reads,
//! with its current default, every line commented out. `examples/rime.toml`
//! is this output checked in; `tests/config_template.rs` fails when the two
//! drift, so regenerating it is part of adding a rule, changing a default,
//! or bumping the version (see CLAUDE.md).

use rime_check::rules::module_scope;
use rime_check::rules::retention;
use rime_diag::{rule_default, Code, Severity, RULE_NAMES};

/// One header per hundred-block, in code order.
const FAMILIES: &[(u16, &str)] = &[
    (0, "R00xx — syntax, dialect, and scope"),
    (100, "R01xx — control flow"),
    (200, "R02xx — nil narrowing"),
    (300, "R03xx — calls and module members"),
    (400, "R04xx — frozen tables"),
    (500, "R05xx — requires"),
    (600, "R06xx — suspicious code (selene parity)"),
    (700, "R07xx — style (selene parity)"),
    (800, "R08xx — Roblox"),
    (900, "R09xx — internal"),
];

pub fn render() -> String {
    let mut s = String::new();
    let mut line = |text: &str| {
        s.push_str(text);
        s.push('\n');
    };

    line("# rime.toml — every setting Rime reads, with its current default.");
    line("#");
    line(&format!(
        "# Generated by `rime config-template` (rime {}). Regenerate and commit",
        env!("CARGO_PKG_VERSION")
    ));
    line("# before each release:");
    line("#     cargo run -p rime-cli -- config-template --out examples/rime.toml");
    line("# Every line is commented out, so copying this file changes nothing;");
    line("# uncomment a line to change that setting.");
    line("");
    line("# Directories (relative to this file) whose files produce no reports.");
    line("# Interfaces are still extracted from them, so cross-file checks of the");
    line("# kept files are unaffected. Default: none.");
    line("# ignore = [\"Packages\", \"ServerPackages\"]");
    line("");
    line("# The Rojo project file read for cross-file checks (relative to this");
    line("# file). `--project <file>` overrides it. Default: the nearest folder at");
    line("# or above the checked path that holds a *.project.json; there,");
    line("# default.project.json wins, one file under another name is used, and");
    line("# several with no default turn cross-file checks off with a message.");
    line("# project = \"default.project.json\"");
    line("");
    line("# [requires]");
    line("# DataModel-path patterns whose requires you vouch for when resolution");
    line("# misses: `*` matches one segment, `**` a whole subtree. Consulted only");
    line("# after a real resolution miss. Default: none.");
    line("# trust = [\"game.ReplicatedStorage.Vendor.**\"]");
    line("");
    line("# [std]");
    line("# selene-format std-library YAML files that REPLACE the bundled");
    line("# lua51 + luau + roblox set. Default: the bundled set.");
    line("# files = [\"std/roblox.yml\"]");
    line("# Extra global names on top of whichever set `files` selects. Default: none.");
    line("# globals = [\"it\", \"expect\", \"describe\"]");
    line("");
    line("# [names]");
    line("# Variable names the player-map rules (R0802, R0803) read as \"this holds");
    line("# a Player\" when the variable is used as a table key. A `Player`");
    line("# annotation always counts, listed or not. `*` matches any run of");
    line("# characters (`*Player`); `[]` leaves only the annotations.");
    line(&format!(
        "# player = [{}]",
        retention::DEFAULT_PLAYER_NAMES.iter().map(|n| format!("\"{n}\"")).collect::<Vec<_>>().join(", ")
    ));
    line("");
    line("# [conservative]");
    line("# Some reports are Rime's stated limitations rather than proof of a bug");
    line("# (rendered `(conservative)`, `\"conservative\": true` in --format json).");
    line("# This downgrades every such report on top of its rule's level; it can");
    line("# never raise one. Default: the rule's own level.");
    line("# default = \"warn\"");
    line("");
    line("# [custom-rules]");
    line("# The directory custom rules (rime-rules/*.luau beside this file) see");
    line("# paths relative to: each rule's `file.path` and `files` globs. Files");
    line("# outside it are not checked by custom rules, and the run says how many.");
    line("# Set it when this file lives below the project root. Default: this");
    line("# file's own directory.");
    line("# root = \"..\"");
    line("");
    line("# Custom rules from rime-rules/*.luau are keyed by their id under [rules]");
    line("# exactly like core rules, e.g. `my-rule = \"off\"`.");
    line("");
    line("[rules]");
    line("# Values: \"error\" | \"warn\" | \"off\", or a table that treats the rule's");
    line("# conservative reports separately (see [conservative] above), e.g.");
    line("#     possible-nil-use = { level = \"error\", conservative = \"off\" }");
    line("# `level` defaults to the rule's default; `conservative` to [conservative]");
    line("# default, then `level`. A level can turn a rule off, lower an \"error\"");
    line("# rule to \"warn\", or raise a \"warn\" rule to \"error\" so it fails the");
    line("# run; `conservative` only lowers. Raw codes work as keys too, as in");
    line("# `R0041 = \"warn\"`.");

    let mut family = None;
    for (name, code) in RULE_NAMES {
        let block = (code / 100) * 100;
        if family != Some(block) {
            family = Some(block);
            let title = FAMILIES
                .iter()
                .find(|(b, _)| *b == block)
                .map(|(_, t)| *t)
                .unwrap_or("other");
            line("");
            line(&format!("# {title}"));
        }
        let (severity, summary) = rule_default(Code(*code))
            .unwrap_or_else(|| panic!("R{code:04} {name} has no RULE_DEFAULTS entry"));
        let value = match severity {
            _ if rime_diag::off_by_default(Code(*code)) => "off",
            Severity::Error => "error",
            Severity::Warning => "warn",
        };
        line(&format!("# R{code:04} {name} — {summary}"));
        if *code == 312 {
            let list = |items: &[&str]| {
                items.iter().map(|i| format!("\"{i}\"")).collect::<Vec<_>>().join(", ")
            };
            let builtin: Vec<&str> = module_scope::Builtin::ALL.iter().map(|b| b.name()).collect();
            let always: Vec<String> =
                module_scope::ALWAYS_ALLOWED.iter().map(|c| format!("`{c}`")).collect();
            line("# Off until it is given a level. It takes settings of its own, as a");
            line("# table with the level beside them (each shown at its default):");
            line("#     [rules.module-scope-computation]");
            line("#     level = \"error\"");
            line("# The built-in lists of calls a module may make as it loads:");
            line("#   luau: the Luau library that works on the values it is given");
            line("#   (`math.*`, `string.*`, `table.*`, `bit32.*`, `utf8.*`, `buffer.*`,");
            line("#   `vector.*`) and the builtins of the same kind (`typeof`,");
            line("#   `setmetatable`, `pairs`, ...).");
            line("#   roblox-datatypes: constructors of Roblox value types (`Vector3.new`,");
            line("#   `CFrame.Angles`, `Color3.fromRGB`, ...). Not `Instance.new`, not");
            line("#   services.");
            line("# `[]` uses neither.");
            line(&format!("#     allow-builtin = [{}]", list(&builtin)));
            line("# More callees, added to the built-in lists. Written as in the source;");
            line("# `*` is any run of characters (`Signal.new`, `*.new`, `*:IsServer`).");
            line("#     allow = []");
            line("# Callees reported whatever the lists above say (`Random.new`).");
            line("#     deny = []");
            line(&format!("# {} are allowed without being listed;", always.join(" and ")));
            line("# `deny` takes them out too.");
            line("# Whether a module may loop as it loads. Calls inside are then checked.");
            line("#     allow-loops = false");
            line("# Entry scripts, left alone. The default is the names Rojo makes a");
            line("# script of; a project with `syncRules` of its own lists its own.");
            line("# An entry is a file name, or with a `/` a path below this file");
            line("# (`*` stays in one folder, `**` does not). A pattern with no `*`");
            line("# in its last part is also a folder below this file, and everything");
            line("# under it. A file that returns no value is never a module,");
            line("# whatever its name.");
            line("#     scripts = [");
            for pair in module_scope::DEFAULT_SCRIPTS.chunks(2) {
                line(&format!("#         {},", list(pair)));
            }
            line("#     ]");
            line("# Other files and folders the rule leaves alone. Same patterns.");
            line("#     exclude = []");
        } else if rime_diag::off_by_default(Code(*code)) {
            line("# Off until it is given a level, \"warn\" or \"error\": a convention a");
            line("# project chooses.");
        }
        if Code(*code) == rime_diag::INTERNAL_ERROR {
            line("# Always reported, whatever is set here: it also survives `ignore`,");
            line("# `--only`, and inline allows, and makes `rime check` exit 101.");
        }
        line(&format!("# {name} = \"{value}\""));
    }
    s
}
